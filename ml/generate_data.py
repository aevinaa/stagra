"""Generate SYNTHETIC ESP32-style air-quality data.

*** SYNTHETIC / TEST DATA ONLY ***
This data exists to exercise the ML pipeline (preprocessing, features, later
training code). It is NOT a measurement and must never be used as the research
dataset or reported as a result. `mq135_raw` is an arbitrary ADC-like number
from a toy model; it is not a calibrated gas concentration (no CO2/CO/VOC/AQI).

The label travels with the data without adding columns (the columns must match
the planned real dataset): the file name starts with SYNTHETIC_, experiment ids
start with "SYNTH-", locations start with "synthetic_", and a sidecar
`<file>.meta.json` records the seed and settings.

Run from the project root:
    python -m ml.generate_data
    python -m ml.generate_data --experiments 12 --hours 2 --seed 7 --fault-rate 0
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "data" / "synthetic" / "SYNTHETIC_test_readings.csv"

COLUMNS = [
    "timestamp",
    "temperature_c",
    "humidity_percent",
    "mq135_raw",
    "experiment_id",
    "location",
    "occupancy",
    "ventilation",
    "fan",
    "ac",
]

NOTICE = (
    "SYNTHETIC TEST DATA generated by ml/generate_data.py for testing the ML pipeline only. "
    "These are NOT real measurements: do not use them as the research dataset or report any "
    "result computed from them. mq135_raw values are arbitrary simulated ADC-like numbers, "
    "not calibrated gas concentrations."
)

# Fixed start so the same seed always gives the same file.
BASE_START = pd.Timestamp("2026-01-05T08:00:00Z")

# Pseudo-rooms; a larger volume factor means pollutant builds up more slowly.
ROOMS = {"synthetic_room_a": 1.0, "synthetic_room_b": 1.6}

# ---- Toy model constants: ARBITRARY UNITS, not calibrated to anything real ----
CLEAN_AIR_RAW = 300.0  # simulated raw value with no pollutant
RAW_PER_UNIT = 0.9  # simulated raw counts per unit of "pollution level"
GEN_PER_PERSON = 1.5  # pollution units generated per person per minute
DECAY_CLOSED = 0.010  # 1/min, closed room, fan off
DECAY_OPEN_EXTRA = 0.060  # extra 1/min when ventilation is open
DECAY_FAN_EXTRA = 0.030  # extra 1/min when the fan is on
DECAY_AC_EXTRA = 0.008  # extra 1/min when the AC is on

FAULT_KINDS = [
    "temp_disconnected",  # DS18B20 reports -127 when the probe is disconnected
    "temp_power_on_reset",  # DS18B20 reports 85 after a power-on reset
    "humidity_missing",  # DHT11 read failure
    "mq135_missing",
    "timestamp_without_timezone",
    "invalid_ventilation",
]


def _schedule(rng, n_steps, interval_seconds, has_ac):
    """Piecewise-constant conditions: they change every 30-90 minutes."""
    occupancy = np.zeros(n_steps, dtype=int)
    vent_open = np.zeros(n_steps, dtype=bool)
    fan_on = np.zeros(n_steps, dtype=bool)
    ac_on = np.zeros(n_steps, dtype=bool)
    i = 0
    while i < n_steps:
        length = max(1, int(rng.integers(30, 91) * 60 / interval_seconds))
        j = min(n_steps, i + length)
        occupancy[i:j] = rng.choice([0, 0, 1, 2, 3, 4, 6])
        vent_open[i:j] = rng.random() < 0.35
        fan_on[i:j] = rng.random() < 0.40
        ac_on[i:j] = has_ac and rng.random() < 0.50
        i = j
    return occupancy, vent_open, fan_on, ac_on


def _simulate_experiment(rng, index, n_steps, interval_seconds):
    room = list(ROOMS)[index % len(ROOMS)]
    volume = ROOMS[room]
    has_ac = bool(rng.random() < 0.5)  # "ac if available"
    base_temp = rng.uniform(23.0, 26.0)
    base_hum = rng.uniform(45.0, 60.0)
    start = BASE_START + pd.Timedelta(days=index, hours=int(rng.choice([0, 2, 5, 7])))

    occupancy, vent_open, fan_on, ac_on = _schedule(rng, n_steps, interval_seconds, has_ac)
    timestamps = pd.date_range(start, periods=n_steps, freq=f"{interval_seconds}s")
    hours = (timestamps.hour + timestamps.minute / 60.0).to_numpy()
    dt_min = interval_seconds / 60.0

    level = rng.uniform(0.0, 80.0)  # leftover pollution from before the experiment
    temp = base_temp + rng.normal(0, 0.3)
    hum = base_hum + rng.normal(0, 2.0)
    level_arr = np.empty(n_steps)
    temp_arr = np.empty(n_steps)
    hum_arr = np.empty(n_steps)

    for t in range(n_steps):
        # Pollution: first-order mass balance, solved exactly for any interval.
        k = (
            DECAY_CLOSED
            + DECAY_OPEN_EXTRA * vent_open[t]
            + DECAY_FAN_EXTRA * fan_on[t]
            + DECAY_AC_EXTRA * ac_on[t]
        )
        steady = GEN_PER_PERSON * occupancy[t] / volume / k
        level = steady + (level - steady) * np.exp(-k * dt_min)

        # Temperature relaxes toward a target set by time of day, people and AC.
        temp_target = (
            base_temp + np.sin(2 * np.pi * (hours[t] - 9) / 24) + 0.35 * occupancy[t] - 3.0 * ac_on[t]
        )
        temp = temp_target + (temp - temp_target) * np.exp(-dt_min / 30.0)

        # Humidity: people add, open windows let in humid outdoor air, AC dries.
        hum_target = base_hum + 1.5 * occupancy[t] + 4.0 * vent_open[t] - 6.0 * ac_on[t]
        hum = hum_target + (hum - hum_target) * np.exp(-dt_min / 20.0)

        level_arr[t], temp_arr[t], hum_arr[t] = level, temp, hum

    # Sensor effects: DS18B20 steps of 0.0625 C, DHT11 whole-percent steps (20-90 %).
    temperature = np.round((temp_arr + rng.normal(0, 0.08, n_steps)) / 0.0625) * 0.0625
    humidity = np.clip(np.round(hum_arr + rng.normal(0, 0.8, n_steps)), 20, 90)
    raw = CLEAN_AIR_RAW + RAW_PER_UNIT * level_arr + 0.8 * (hum_arr - 50.0) + rng.normal(0, 6.0, n_steps)
    mq135 = np.clip(np.round(raw), 0, 4095).astype(int)  # 12-bit ADC range

    return pd.DataFrame(
        {
            "timestamp": timestamps,
            "temperature_c": np.round(temperature, 4),
            "humidity_percent": humidity,
            "mq135_raw": mq135,
            "experiment_id": f"SYNTH-{index + 1:03d}",
            "location": room,
            "occupancy": occupancy,
            "ventilation": np.where(vent_open, "open", "closed"),
            "fan": np.where(fan_on, "on", "off"),
            "ac": np.where(ac_on, "on", "off") if has_ac else None,
        }
    )


def _inject_faults(df, rng, rate):
    """Mimic what real ESP32 logs look like so preprocessing has work to do."""
    df = df.reset_index(drop=True).copy()
    n = len(df)

    hit = rng.random(n) < rate
    kind = rng.integers(0, len(FAULT_KINDS), n)

    def rows(name):
        return hit & (kind == FAULT_KINDS.index(name))

    df.loc[rows("temp_disconnected"), "temperature_c"] = -127.0
    df.loc[rows("temp_power_on_reset"), "temperature_c"] = 85.0
    df.loc[rows("humidity_missing"), "humidity_percent"] = np.nan
    df.loc[rows("mq135_missing"), "mq135_raw"] = pd.NA
    m = rows("timestamp_without_timezone")
    df.loc[m, "timestamp"] = df.loc[m, "timestamp"].str.rstrip("Z")
    df.loc[rows("invalid_ventilation"), "ventilation"] = "ajar"

    # Dropped readings: isolated ones, plus one longer burst in some experiments.
    keep = rng.random(n) >= rate / 2
    for positions in df.groupby("experiment_id").indices.values():
        if len(positions) > 40 and rng.random() < 0.3:
            length = int(rng.integers(8, 21))
            s = int(rng.integers(0, len(positions) - length))
            keep[positions[s : s + length]] = False
    df = df[keep]

    # Duplicated rows appended at the end, then a few rows moved out of order.
    dup = df.sample(frac=rate / 2, random_state=int(rng.integers(0, 2**31 - 1)))
    df = pd.concat([df, dup], ignore_index=True)
    order = np.arange(len(df))
    moved = rng.choice(len(df), size=max(2, int(len(df) * rate)), replace=False)
    order[moved] = rng.permutation(moved)
    return df.iloc[order].reset_index(drop=True)


def generate(n_experiments=24, hours=4.0, interval_seconds=60, seed=42, fault_rate=0.01):
    """Return a synthetic DataFrame with exactly the planned dataset columns."""
    if n_experiments < 1:
        raise ValueError("n_experiments must be at least 1")
    if interval_seconds < 1:
        raise ValueError("interval_seconds must be at least 1")
    if not 0 <= fault_rate <= 0.2:
        raise ValueError("fault_rate must be between 0 and 0.2")
    n_steps = int(hours * 3600 / interval_seconds)
    if n_steps < 2:
        raise ValueError("hours / interval_seconds gives fewer than 2 samples per experiment")

    rng = np.random.default_rng(seed)
    frames = [_simulate_experiment(rng, i, n_steps, interval_seconds) for i in range(n_experiments)]
    df = pd.concat(frames, ignore_index=True)
    df["timestamp"] = df["timestamp"].dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    df["mq135_raw"] = df["mq135_raw"].astype("Int64")  # allows blanks, no ".0" in the CSV
    if fault_rate > 0:
        df = _inject_faults(df, rng, fault_rate)
    return df[COLUMNS]


def write_dataset(df, output, settings):
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output, index=False)
    meta = {"synthetic": True, "notice": NOTICE, "rows": int(len(df)), **settings}
    meta_path = output.with_name(output.name + ".meta.json")
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    return meta_path


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Generate SYNTHETIC test data for the ML pipeline.")
    p.add_argument("--experiments", type=int, default=24)
    p.add_argument("--hours", type=float, default=4.0, help="duration of each experiment")
    p.add_argument("--interval-seconds", type=int, default=60)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--fault-rate", type=float, default=0.01, help="0 disables injected faults")
    p.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = p.parse_args(argv)

    try:
        df = generate(args.experiments, args.hours, args.interval_seconds, args.seed, args.fault_rate)
    except ValueError as e:
        p.error(str(e))

    settings = {
        "seed": args.seed,
        "experiments": args.experiments,
        "hours_per_experiment": args.hours,
        "interval_seconds": args.interval_seconds,
        "fault_rate": args.fault_rate,
    }
    meta_path = write_dataset(df, args.output, settings)
    print("=" * 72)
    print("SYNTHETIC TEST DATA - not real measurements, not for research results")
    print("=" * 72)
    print(f"wrote {len(df)} rows -> {args.output}")
    print(f"wrote metadata   -> {meta_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())