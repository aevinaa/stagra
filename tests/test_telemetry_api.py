# ================================================================ history: long histories
def _series(n, spike_at=None, dip_at=None, step_s=10, exp="E1", start=None):
    start = start or NOW - timedelta(seconds=step_s * n)
    rows = []
    for i in range(n):
        mq = 300.0 + (i % 17)
        if i == spike_at:
            mq = 900.0
        if i == dip_at:
            mq = 5.0
        rows.append(reading(start + timedelta(seconds=step_s * i), mq=mq, exp=exp))
    return rows


def test_long_history_is_downsampled_keeping_peaks_and_real_rows(env):
    add(env, _series(1000, spike_at=500, dip_at=250))
    before = snapshot(env)
    body = history(env, range="24h", max_points=100)
    meta, pts = body["meta"], body["readings"]
    assert len(pts) <= 100 and meta["count"] == len(pts)
    assert meta["sourceCount"] == 1000 and meta["downsampled"] is True and meta["method"] == "min_max_per_group"
    assert meta["groupSize"] == 21  # ceil(1000 / ((100 - 2) // 2))
    assert "1000" in meta["note"] and "21" in meta["note"] and "highest and lowest" in meta["note"]
    stamps = [parse(p["timestamp"]) for p in pts]
    assert stamps == sorted(stamps) and len(set(stamps)) == len(stamps)  # chronological, no repeats
    assert 900.0 in mqs(body) and 5.0 in mqs(body)  # the single spike and the single dip survive
    stored = {r[1]: r for r in before}  # timestamp -> stored row
    for p in pts:  # every point is an untouched stored reading
        row = stored[parse(p["timestamp"])]
        assert (p["temperature"], p["humidity"], p["mq135"]) == (row[2], row[3], row[4])
    assert stamps[0] == min(stored) and stamps[-1] == max(stored)  # first and last reading kept
    assert snapshot(env) == before  # the database is untouched


def test_history_under_the_limit_is_not_reduced(env):
    add(env, _series(100))
    for mp in (100, 101, 1000):
        body = history(env, range="24h", max_points=mp)
        assert body["meta"]["downsampled"] is False and body["meta"]["method"] == "none"
        assert body["meta"]["count"] == body["meta"]["sourceCount"] == 100 == len(body["readings"])
    assert history(env, range="24h", max_points=99)["meta"]["downsampled"] is True  # one over the limit


@pytest.mark.parametrize("count", [1, 2, 3, 4, 5, 99, 100, 101, 1000])
@pytest.mark.parametrize("max_points", [4, 5, 7, 100])
def test_history_never_returns_more_than_max_points(env, count, max_points):
    rng = np.random.default_rng(count * 1000 + max_points)
    values = rng.integers(100, 900, size=count).astype(float)
    start = NOW - timedelta(seconds=10 * count)
    add(env, [reading(start + timedelta(seconds=10 * i), mq=float(v)) for i, v in enumerate(values)])
    body = history(env, range="24h", max_points=max_points)
    pts = body["readings"]
    assert len(pts) <= max_points and body["meta"]["sourceCount"] == count
    stamps = [parse(p["timestamp"]) for p in pts]
    assert stamps == sorted(stamps)
    if count <= max_points:
        assert len(pts) == count and not body["meta"]["downsampled"]
    else:
        assert body["meta"]["downsampled"]
        assert stamps[0] == start and stamps[-1] == start + timedelta(seconds=10 * (count - 1))
        assert max(mqs(body)) == values.max() and min(mqs(body)) == values.min()  # global extremes survive


def test_downsampling_equal_values_is_deterministic_and_bounded(env):
    add(env, [reading(NOW - timedelta(seconds=10 * (1000 - i)), mq=300.0) for i in range(1000)])
    a, b = history(env, max_points=100), history(env, max_points=100)
    assert a["readings"] == b["readings"] and 2 <= len(a["readings"]) <= 100


def test_history_query_is_bounded_by_a_sql_limit(env):
    add(env, _series(200))
    statements = []

    @event.listens_for(env.engine, "before_cursor_execute")
    def capture(conn, cursor, statement, parameters, context, executemany):
        statements.append((statement, parameters))

    history(env, range="24h", max_points=50)
    main = [(s, p) for s, p in statements if "numbered" in s]
    assert main and all("LIMIT ?" in s for s, _ in main)
    assert all(50 in p for _, p in main)  # the limit parameter is max_points
    assert not any(s.strip().upper().startswith(("INSERT", "UPDATE", "DELETE")) for s, _ in statements)


