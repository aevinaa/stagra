    assert body["experimentId"] == "exp-9" and body["location"] == "lab-2"
    assert body["occupancyInferred"] is False and body["ventilationInferred"] is False
    assert body["isSynthetic"] is False
    assert parse(body["timestamp"]) == NOW - timedelta(seconds=10) and parse(body["timestamp"]).tzinfo is not None


