def reading(ts, mq=300.0, exp="E1", loc="lab", temp=22.0, hum=50.0, occ=1, vent="closed", fan="off", ac=None):
    return Reading(
        timestamp=ts, temperature_c=temp, humidity_percent=hum, mq135_raw=mq, experiment_id=exp,
        location=loc, occupancy=occ, ventilation=vent, fan=fan, ac=ac,
    )


def add(env, rows):
    with env.Session() as db:
        db.add_all(rows)
        db.commit()


def snapshot(env):
    """Every stored row, exactly as in the database (to prove the endpoints never change data)."""
    with env.Session() as db:
        rows = db.scalars(select(Reading).order_by(Reading.id)).all()
        return [
            (r.id, r.timestamp, r.temperature_c, r.humidity_percent, r.mq135_raw, r.experiment_id,
             r.location, r.occupancy, r.ventilation, r.fan, r.ac)
            for r in rows
        ]


def parse(ts: str) -> datetime:
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


def history(env, **params):
    r = env.client.get("/api/telemetry/history", params=params)
    assert r.status_code == 200, r.text
    return r.json()


def mqs(body):
    return [p["mq135"] for p in body["readings"]]


