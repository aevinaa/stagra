def test_history_on_empty_database_is_an_explicit_empty_result(env):
    body = history(env)
    assert body["readings"] == []
    meta = body["meta"]
    assert set(meta) == META_KEYS
    assert meta["count"] == 0 and meta["sourceCount"] == 0 and meta["downsampled"] is False
    assert meta["method"] == "none" and meta["groupSize"] is None and "0" in meta["note"]


def test_history_response_schema_and_default_window(env):
    add(env, [reading(NOW - timedelta(hours=2), mq=500.0, exp="SYNTH-7"), reading(NOW - timedelta(days=2), mq=1.0)])
    body = history(env)
    assert set(body) == {"readings", "meta"}
    assert len(body["readings"]) == 1  # default window = last 24 h
    point = body["readings"][0]
    assert set(point) == POINT_KEYS
    assert point["mq135"] == 500.0 and point["experimentId"] == "SYNTH-7" and point["isSynthetic"] is True
    meta = body["meta"]
    assert set(meta) == META_KEYS
    assert meta["range"] == "24h" and meta["anchor"] == "now" and meta["order"] == "ascending"
    assert parse(meta["windowEnd"]) == NOW and parse(meta["windowStart"]) == NOW - timedelta(hours=24)
    assert meta["maxPoints"] == 1000 and meta["experimentId"] is None
    assert "airquality" not in str(body).lower()


def test_history_is_chronological_even_when_inserted_out_of_order(env):
    t = NOW - timedelta(hours=1)
    add(env, [
        reading(t + timedelta(seconds=20), mq=3.0),
        reading(t, mq=1.0),
        reading(t + timedelta(seconds=10), mq=2.0),
        reading(t + timedelta(seconds=10), mq=2.5),  # same timestamp: later id comes later
    ])
    body = history(env, range="1h")
    assert mqs(body) == [1.0, 2.0, 2.5, 3.0]
    stamps = [parse(p["timestamp"]) for p in body["readings"]]
    assert stamps == sorted(stamps)


def test_history_returns_real_stored_values_and_timestamps(env):
    rows = [reading(NOW - timedelta(minutes=m), mq=300.0 + m, temp=20.0 + m / 10, hum=40.0 + m / 7) for m in range(1, 8)]
    expected = sorted(((r.timestamp, r.temperature_c, r.humidity_percent, r.mq135_raw) for r in rows))  # before commit
    add(env, rows)
    body = history(env, range="1h")
    got = [(parse(p["timestamp"]), p["temperature"], p["humidity"], p["mq135"]) for p in body["readings"]]
    assert got == expected
    assert all(parse(p["timestamp"]).tzinfo is not None for p in body["readings"])


def test_history_does_not_change_stored_data(env):
    add(env, [reading(NOW - timedelta(seconds=10 * i), mq=300.0 + (i % 11)) for i in range(300)])
