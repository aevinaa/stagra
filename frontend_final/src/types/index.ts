export type AirQualityLevel = 'Low' | 'Moderate' | 'High';

export type OccupancyLevel = 'Vacant' | 'Low' | 'Moderate' | 'High';

export type VentilationStatus = 'Off' | 'Natural' | 'Low' | 'Moderate' | 'High';

export type PredictionTrend = 'Increasing' | 'Improving' | 'Stable' | 'Worsening';

export type TimeRange = '1h' | '6h' | '24h' | '7d';

/**
 * 1. Current sensor conditions received from Backend API.
 * Sensor values originating from the ESP32 node (DHT22, MQ135)
 * ingested and served through the backend server.
 */
export interface CurrentConditions {
  temperature: number; // in degrees Celsius (°C)
  humidity: number; // in relative humidity percentage (%RH)
  mq135: number; // raw sensor reading in sensor units (uncalibrated)
  airQuality: AirQualityLevel; // Project-defined air quality classification ('Low' | 'Moderate' | 'High')
  timestamp: string; // ISO 8601 string or UTC timestamp
  occupancy: OccupancyLevel; // Room occupancy level
  ventilation: VentilationStatus; // Ventilation state
  occupancyInferred?: boolean; // True only if data layer specifically provides an inference
  ventilationInferred?: boolean; // True only if data layer specifically provides an inference
  // Optional hardware status attached to telemetry packet
  sensorStatus?: {
    dht22: 'Operational' | 'Degraded' | 'Offline';
    mq135: 'Operational' | 'Warming Up' | 'Offline';
  };
}

/**
 * Single step in the prediction horizon / timeline forecast.
 */
export interface ForecastStep {
  minutesAhead: number; // 0, 5, 10, 15
  label: string; // e.g. "Current", "After 5 minutes", "After 10 minutes", "After 15 minutes"
  airQuality: AirQualityLevel; // 'Low' | 'Moderate' | 'High'
  predictedMq135?: number; // projected sensor reading
  confidence?: number; // optional step-level confidence
}

/**
 * 2. Prediction payload generated by the backend ML service / forecast model.
 */
export interface AirQualityPrediction {
  currentLevel: AirQualityLevel; // Current starting classification
  forecast: ForecastStep[]; // Timeline forecast steps (0m, +5m, +10m, +15m)
  predictionHorizonMinutes: number; // Total forecast horizon (e.g. 10 or 15 minutes)
  confidence: number; // Prediction confidence (e.g. 0.87 for 87%)
  trend: PredictionTrend; // Trajectory: 'Increasing' | 'Improving' | 'Stable' | 'Worsening'
  modelUsed: string; // Name of model/algorithm producing forecast (e.g. "Transformer", "Linear Extrapolation (Demo)")
  recommendation: string; // Actionable HVAC or ventilation recommendation

  // Compatibility aliases supporting existing component views
  predictedAirQuality?: AirQualityLevel; // alias for the target forecast level
  horizonMinutes?: number; // alias for predictionHorizonMinutes
  targetTime?: string; // ISO timestamp corresponding to forecast target
  timelineForecasts?: ForecastStep[]; // alias for forecast
  multiHorizonForecasts?: {
    horizonMinutes: number;
    predictedAirQuality: AirQualityLevel;
    confidence: number;
    projectedMq135: number;
  }[];
}

/**
 * 3. Historical time-series reading for continuous trend plotting and historical analysis.
 */
export interface HistoricalReading {
  timestamp: string; // ISO 8601 string
  temperature: number; // in degrees Celsius (°C)
  humidity: number; // in relative humidity percentage (%RH)
  mq135: number; // raw sensor reading in sensor units
  airQuality: AirQualityLevel; // Project-defined classification ('Low' | 'Moderate' | 'High')
}

/**
 * 4. Model benchmark and comparison metrics for research/experimental evaluation.
 */
export interface ModelComparisonResult {
  modelName: string; // 'LSTM' | 'GRU' | 'Transformer'
  mae: number; // Mean Absolute Error
  rmse: number; // Root Mean Square Error
  accuracy: number; // Classification accuracy (0.0 to 1.0 or percentage)
  f1Score?: number; // Optional F1 Score
  status: 'Evaluated' | 'Production Candidate' | 'Baseline' | 'Benchmarked';
  parametersCount?: string; // Parameter count / model size
  inferenceLatencyMs?: number; // Edge/backend inference latency
  notes?: string;
}

// Backward-compatible alias for existing views
export type ModelComparisonMetric = ModelComparisonResult;

/**
 * 5. System and sensor health status.
 * Monitored link between the ESP32 hardware and the Backend API ingestion server.
 */
export interface SystemStatus {
  esp32Connected: boolean; // Link state between ESP32 hardware and Backend API
  lastPacketTime: string; // ISO 8601 timestamp of most recent sensor packet
  sensorStatus: {
    dht22: 'Operational' | 'Degraded' | 'Offline';
    mq135: 'Operational' | 'Warming Up' | 'Offline';
  };
  mcuNode?: string; // e.g. "ESP32 DevKit-V1"
  samplingIntervalSeconds?: number; // e.g. 5
  room?: string; // e.g. "Room 204"
  activeSensors?: string[];
}

/**
 * Summary telemetry envelope for high-level monitoring views.
 */
export interface TelemetrySummary {
  current: CurrentConditions;
  prediction: AirQualityPrediction;
  system: SystemStatus;
  historyCount: number;
  averageMq135Past24h: number;
  peakMq135Past24h: number;
}

